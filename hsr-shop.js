export const hsrShopKey = value => String(value ?? '').normalize('NFKC').trim().replace(/\s+/g, ' ').toLowerCase();

export const HSR_SHOP = {
  currency: { name: 'Credits', icon: 'fa-coins' },
  start: 0,
  items: [...markets, ...locationTypes].flatMap(({ id: area, goods }) =>
    goods.map(([id, name, price, cat, desc]) => ({ id: `hsr:${area}:${id}`, area, name, price, cat, desc }))),
};

export function hsrLocalShop(items, location) {
  const place = hsrShopKey(location);
  const market = markets.find(({ match }) => match?.test(place));
  const local = locationTypes.find(({ match }) => match.test(place));
  const areas = ['supply', market?.id, local?.id].filter(Boolean);
  const shelf = items.flatMap(item => {
    if (item.locations) {
      const offer = item.locations.get(place);
      return offer ? [{ ...item, ...offer }] : [];
    }
    return item.own || areas.includes(item.area) ? [item] : [];
  });
  return { name: local?.name || market?.name || markets[0].name, items: shelf };
}

export function hsrStoryStock(listings) {
  const shelves = new Map();
  for (const [location, offers] of listings) {
    if (location) shelves.set(hsrShopKey(location), offers);
  }
  const items = new Map();
  for (const [location, offers] of shelves) {
    for (const offer of offers) {
      if (!items.has(offer.id)) items.set(offer.id, { ...offer, locations: new Map() });
      items.get(offer.id).locations.set(location, offer);
    }
  }
  return [...items.values()];
}
